const MONTH_MAP: Record<string, number> = {
  'января': 0, 'февраля': 1, 'марта': 2, 'апреля': 3, 'мая': 4, 'июня': 5,
  'июля': 6, 'августа': 7, 'сентября': 8, 'октября': 9, 'ноября': 10, 'декабря': 11,
};

function parseMeetingDateTime(m: Meeting): Date | null {
  if (m.dateTime) {
    const d = new Date(m.dateTime);
    if (!isNaN(d.getTime())) return d;
  }
  const match = m.date.match(/(\d{1,2})\s+([а-яё]+)/i);
  if (!match) return null;
  const day = parseInt(match[1]);
  const month = MONTH_MAP[match[2].toLowerCase()];
  if (month === undefined) return null;
  const timeMatch = m.time.match(/(\d{2}):(\d{2})/);
  if (!timeMatch) return null;
  return new Date(new Date().getFullYear(), month, day, parseInt(timeMatch[1]), parseInt(timeMatch[2]));
}

function classifyMeetings(meetings: Meeting[]): Meeting[] {
  const now = Date.now();
  const DAY = 24 * 60 * 60 * 1000;
  return meetings
    .map((m) => {
      if (m.status === 'completed') return m;
      const dt = parseMeetingDateTime(m);
      if (!dt) return m;
      const diff = dt.getTime() - now;
      if (diff < 0) return { ...m, status: 'completed' as const };
      if (diff < DAY) return { ...m, status: 'upcoming' as const };
      return { ...m, status: 'scheduled' as const };
    })
    .sort((a, b) => {
      const da = parseMeetingDateTime(a)?.getTime() || 0;
      const db = parseMeetingDateTime(b)?.getTime() || 0;
      return da - db;
    });
}

